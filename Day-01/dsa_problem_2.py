import math
a=int(input())
for i in range(a):
    b=int(input())
    print(math.factorial(b))

# They want to find the factorial of a number. So we will use the math library in python which has a built-in function called factorial() that takes an integer as input and returns its factorial. We will take the input from the user and pass it to the factorial() function and print the result. 